// Packs every file in /public into src/generated/assets.js so the Worker can
// serve the pages itself. Runs automatically before each deploy (see wrangler.jsonc).
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative, extname, dirname } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");
const outFile = join(root, "src", "generated", "assets.js");

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
};
const TEXT = new Set([".html", ".css", ".js", ".json", ".svg", ".txt"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const assets = {};
for (const file of walk(publicDir)) {
  const rel = "/" + relative(publicDir, file).split("\\").join("/");
  if (rel === "/_headers") continue;
  const ext = extname(file).toLowerCase();
  const buf = readFileSync(file);
  const etag = '"' + createHash("sha256").update(buf).digest("hex").slice(0, 20) + '"';
  assets[rel] = TEXT.has(ext)
    ? { type: TYPES[ext] || "application/octet-stream", etag, text: buf.toString("utf8") }
    : { type: TYPES[ext] || "application/octet-stream", etag, base64: buf.toString("base64") };
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, "// AUTO-GENERATED by scripts/build-assets.mjs. Do not edit.\nexport default " + JSON.stringify(assets) + ";\n");
console.log(`Packed ${Object.keys(assets).length} files from /public`);
